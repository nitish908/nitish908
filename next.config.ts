import type { NextConfig } from "next";

// No nonce: nonce-based CSP requires every page to render dynamically per
// request (see Next.js's CSP guide), which would throw away static
// generation for an app that has no backend and no per-user state to begin
// with. 'unsafe-inline' on script/style is the tradeoff Next.js itself
// documents for apps that stay static — everything else stays locked down,
// and the app has no dangerouslySetInnerHTML / user-rendered HTML anywhere,
// so there's no real inline-injection vector for it to widen.
const csp = [
  "default-src 'self'",
  "script-src 'self' 'unsafe-inline'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' blob: data:",
  "font-src 'self' data:",
  "connect-src 'self'",
  "worker-src 'self' blob:",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
  "upgrade-insecure-requests",
].join("; ");

const securityHeaders = [
  { key: "Content-Security-Policy", value: csp },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  {
    key: "Permissions-Policy",
    value: "camera=(), microphone=(), geolocation=(), interest-cohort=()",
  },
];

const nextConfig: NextConfig = {
  async headers() {
    return [{ source: "/(.*)", headers: securityHeaders }];
  },
};

export default nextConfig;
